type RichTextBlock = { type: 'paragraph'; text: string } | { type: 'list'; items: string[] }

function richText(blocks: RichTextBlock[]) {
  return {
    root: {
      type: 'root',
      children: blocks.map((block) => {
        if (block.type === 'list') {
          return {
            type: 'list',
            listType: 'bullet',
            tag: 'ul',
            start: 1,
            children: block.items.map((text, index) => ({
              type: 'listitem',
              value: index + 1,
              children: [{ type: 'text', text, version: 1 }],
              direction: 'ltr',
              format: '',
              indent: 0,
              version: 1,
            })),
            direction: 'ltr',
            format: '',
            indent: 0,
            version: 1,
          }
        }

        return {
          type: 'paragraph',
          children: [{ type: 'text', text: block.text, version: 1 }],
          direction: 'ltr',
          format: '',
          indent: 0,
          version: 1,
        }
      }),
      direction: 'ltr',
      format: '',
      indent: 0,
      version: 1,
    },
  }
}

